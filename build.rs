use std::collections::HashSet;
use std::fs;
use std::path::Path;

fn entries(directory: &str, suffix: &str) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(directory)
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .filter_map(|entry| entry.file_name().into_string().ok())
                .filter(|name| name.ends_with(suffix))
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    names
}

fn series_variant(stem: &str) -> Option<(String, u32)> {
    let (series, variant) = stem.rsplit_once('-')?;
    let mut parts = series.split('.');
    let major = parts.next()?;
    let minor = parts.next()?;
    if parts.next().is_some() {
        return None;
    }
    if !major.chars().all(|c| c.is_ascii_digit()) || !minor.chars().all(|c| c.is_ascii_digit()) {
        return None;
    }
    let variant = variant.parse().ok()?;
    Some((series.to_string(), variant))
}

fn sort_key(series: &str, variant: u32) -> (u32, u32, u32) {
    let mut parts = series.split('.');
    let major = parts.next().unwrap().parse().unwrap();
    let minor = parts.next().unwrap().parse().unwrap();
    (major, minor, variant)
}

fn main() {
    let stamp = std::process::Command::new("date")
        .args(["-u", "+%Y-%m-%dT%H:%M:%SZ"])
        .output()
        .ok()
        .and_then(|output| String::from_utf8(output.stdout).ok())
        .map(|text| text.trim().to_string())
        .filter(|text| !text.is_empty())
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=BUILD_STAMP={stamp}");

    let mut modules: Vec<(String, u32, String)> = Vec::new();
    let mut seen: HashSet<(String, u32)> = HashSet::new();
    for name in entries("modules", ".ko") {
        let stem = name.trim_end_matches(".ko");
        let (series, variant) = series_variant(stem)
            .unwrap_or_else(|| panic!("invalid module filename: modules/{name}"));
        if !seen.insert((series.clone(), variant)) {
            panic!("duplicate module variant: modules/{name}");
        }
        modules.push((series, variant, name));
    }
    modules.sort_by_key(|(series, variant, _)| sort_key(series, *variant));

    if modules.is_empty() {
        println!("cargo:warning=no kernel modules bundled; MTD unlock will be unavailable");
        if std::env::var("RTL9617C_REQUIRE_MODULES").ok().as_deref() == Some("1") {
            panic!("no kernel modules bundled");
        }
    }

    let mut generated = String::from("// Generated by build.rs. Do not edit.\n\n");

    generated.push_str("/// Board definitions, one file each.\n");
    generated.push_str("pub const BOARD_SOURCES: &[(&str, &str)] = &[\n");
    for name in entries("boards", ".conf") {
        generated.push_str(&format!(
            "    ({name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/boards/{name}\"))),\n"
        ));
    }
    generated.push_str("];\n\n");

    generated.push_str("/// Kernel modules, keyed by kernel series.\n");
    generated.push_str("pub const MODULES: &[(&str, &str, &[u8])] = &[\n");
    for (series, variant, name) in modules {
        generated.push_str(&format!(
            "    ({series:?}, \"{variant}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/modules/{name}\"))),\n"
        ));
    }
    generated.push_str("];\n");

    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("embedded.rs");
    fs::write(&out, generated).expect("writing embedded.rs");
    println!("cargo:rerun-if-changed=boards");
    println!("cargo:rerun-if-changed=modules");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-env-changed=RTL9617C_REQUIRE_MODULES");
}
