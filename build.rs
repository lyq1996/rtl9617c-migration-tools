use std::fs;
use std::path::Path;

fn entries(directory: &str, suffix: &str) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(directory)
        .map(|entries| {
            entries
                .filter_map(|entry| entry.ok())
                .filter_map(|entry| entry.file_name().into_string().ok())
                .filter(|name| name.ends_with(suffix))
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    names
}

fn main() {
    let stamp = std::process::Command::new("date")
        .args(["-u", "+%Y-%m-%dT%H:%M:%SZ"])
        .output()
        .ok()
        .and_then(|output| String::from_utf8(output.stdout).ok())
        .map(|text| text.trim().to_string())
        .filter(|text| !text.is_empty())
        .unwrap_or_else(|| "unknown".to_string());
    println!("cargo:rustc-env=BUILD_STAMP={stamp}");

    let mut generated = String::from("// Generated by build.rs. Do not edit.\n\n");

    generated.push_str("/// Board definitions, one file each.\n");
    generated.push_str("pub const BOARD_SOURCES: &[(&str, &str)] = &[\n");
    for name in entries("boards", ".conf") {
        generated.push_str(&format!(
            "    ({name:?}, include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/boards/{name}\"))),\n"
        ));
    }
    generated.push_str("];\n\n");

    generated.push_str("/// Kernel modules, keyed by the kernel series (major.minor).\n");
    generated.push_str("///\n");
    generated.push_str("/// `modules/6.18.ko` and `modules/6.18.55.ko` both land under `6.18`;\n");
    generated.push_str("/// the loader rewrites the vermagic release to the running kernel.\n");
    generated.push_str("pub const MODULES: &[(&str, &[u8])] = &[\n");
    let mut seen: Vec<String> = Vec::new();
    for name in entries("modules", ".ko") {
        let release = name.trim_end_matches(".ko");
        // "6.18" -> "6.18", "6.18.55" -> "6.18": one module per kernel series.
        let mut parts = release.splitn(3, '.');
        let major = parts.next().unwrap_or(release);
        let series = match parts.next() {
            Some(minor) => format!("{major}.{minor}"),
            None => major.to_string(),
        };
        if seen.contains(&series) {
            panic!("modules/{name}: duplicate for {series}");
        }
        seen.push(series.clone());
        generated.push_str(&format!(
            "    ({series:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/modules/{name}\"))),\n"
        ));
    }
    generated.push_str("];\n");

    let out = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("embedded.rs");
    fs::write(&out, generated).expect("writing embedded.rs");
    println!("cargo:rerun-if-changed=boards");
    println!("cargo:rerun-if-changed=modules");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=Cargo.toml");
}
